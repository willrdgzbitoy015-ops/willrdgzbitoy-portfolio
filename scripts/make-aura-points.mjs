/*
  Makes js/data/aura-points.js: points along Will's outline in the hero photo, used by
  js/aura.js to know where the smoke should rise from.

  How: sharp opens the hero cut-out (it has a transparent background), shrinks it, and
  reads every pixel's transparency ("alpha"). A pixel is on the outline when it is solid
  but touches a see-through neighbour. For each outline pixel we also note which way is
  "outward" (towards the see-through neighbours), so the smoke can drift away from him.

  Why a script and not the browser: a page opened by double-click (file://) is not allowed
  to read an image's pixels, so the points are worked out once here and saved as a file.

  Run it again after changing the hero photo:  npm run aura
*/
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const source = path.join(root, 'images', 'hero-480.webp')
const output = path.join(root, 'js', 'data', 'aura-points.js')

const WIDTH = 120 // working size: small is enough for smoke and keeps the file tiny
const SOLID = 128 // alpha above this counts as "part of Will"
const MAX_Y = 0.8 // skip the bottom 20%: the page fades the photo out there
const KEEP = 170 // how many points to save

const { data, info } = await sharp(source)
  .resize({ width: WIDTH })
  .ensureAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true })
const { width: W, height: H, channels } = info
// Outside the picture counts as solid, so the straight edges where the photo is cropped
// (his arm runs off the left side) don't count as outline.
const alpha = (x, y) =>
  x < 0 || y < 0 || x >= W || y >= H ? 255 : data[(y * W + x) * channels + 3]

const found = []
for (let y = 0; y < H * MAX_Y; y++) {
  for (let x = 0; x < W; x++) {
    if (alpha(x, y) < SOLID) continue
    // Add up the directions to see-through neighbours: that sum points outward.
    let nx = 0
    let ny = 0
    for (let dy = -1; dy <= 1; dy++) {
      for (let dx = -1; dx <= 1; dx++) {
        if ((dx || dy) && alpha(x + dx, y + dy) < SOLID) {
          nx += dx
          ny += dy
        }
      }
    }
    const length = Math.hypot(nx, ny)
    if (!length) continue // fully surrounded: not on the outline
    found.push([(x + 0.5) / W, (y + 0.5) / H, nx / length, ny / length])
  }
}

// Keep an even spread of KEEP points (every n-th one, top to bottom).
const step = Math.max(1, found.length / KEEP)
const points = [] // flat list: x, y, nx, ny, x, y, nx, ny, ...
for (let i = 0; i < found.length; i += step) {
  points.push(...found[Math.floor(i)].map((n) => Math.round(n * 1000) / 1000))
}

writeFileSync(
  output,
  `/*
  GENERATED by scripts/make-aura-points.mjs (npm run aura). Don't edit by hand.
  Points on Will's outline in the hero photo, four numbers each:
    x, y   = where the point is, as a share of the photo's width / height (0 to 1)
    nx, ny = the "outward" direction at that point (away from his body)
*/
window.WB = window.WB || {}
WB.auraPoints = [${points.join(',')}]
`,
)
console.log(`aura-points.js  ${points.length / 4} points (from ${found.length} outline pixels)`)
