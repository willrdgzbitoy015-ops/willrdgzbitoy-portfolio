import type { ReactNode, SVGProps } from 'react'

/*
  Inline SVG icons (no icon library). They are decorative: the button or link
  around them carries the label, so each icon is hidden from screen readers.
*/
type IconProps = SVGProps<SVGSVGElement>

function Icon({ children, ...props }: IconProps & { children: ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      {children}
    </svg>
  )
}

